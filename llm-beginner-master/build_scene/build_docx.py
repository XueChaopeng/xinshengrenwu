def set_font(run, ea="宋体", ascii_="Times New Roman", size=11, bold=False, color=None, italic=False):
    run.font.name = ascii_
    run._element.rPr.rFonts.set(qn("w:eastAsia"), ea)
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color is not None:
        run.font.color.rgb = color


def add_title(text, sub=None):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    set_font(r, ea="黑体", ascii_="SimHei", size=20, bold=True, color=NAVY)
    if sub:
        p2 = doc.add_paragraph()
        p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r2 = p2.add_run(sub)
        set_font(r2, ea="楷体", ascii_="KaiTi", size=13, color=ACC)
    return p


def add_heading(text, level=1):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14)
    p.paragraph_format.space_after = Pt(6)
    r = p.add_run(text)
    if level == 1:
        set_font(r, ea="黑体", ascii_="SimHei", size=15, bold=True, color=NAVY)
    elif level == 2:
        set_font(r, ea="黑体", ascii_="SimHei", size=13, bold=True, color=NAVY)
    else:
        set_font(r, ea="黑体", ascii_="SimHei", size=11.5, bold=True)
    return p


def add_body(text, size=11, indent=True, bold=False):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Cm(0.74)
    p.paragraph_format.line_spacing = 1.35
    r = p.add_run(text)
    set_font(r, size=size, bold=bold)
    return p


def add_bullet(text, size=11):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.line_spacing = 1.3
    r = p.add_run(text)
    set_font(r, size=size)
    return p


def add_picture(path, caption, width=6.2):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(path, width=Inches(width))
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = cap.add_run(caption)
    set_font(r, ea="楷体", ascii_="KaiTi", size=10.5, color=RGBColor(0x55, 0x55, 0x55))


def add_table(headers, rows, widths=None):
    tb = doc.add_table(rows=1, cols=len(headers))
    tb.style = "Table Grid"
    tb.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = tb.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(h)
        set_font(r, ea="黑体", ascii_="SimHei", size=10.5, bold=True, color=NAVY)
        shade_cell(hdr[i], "DCE6F1")
    for row in rows:
        cells = tb.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT if i != 0 else WD_ALIGN_PARAGRAPH.CENTER
            r = p.add_run(str(val))
            set_font(r, size=10.5)
    if widths:
        for row in tb.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return tb


def shade_cell(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hexcolor)
    tcPr.append(shd)


def page_break():
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


